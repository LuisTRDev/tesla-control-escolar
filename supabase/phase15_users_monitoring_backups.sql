-- Fase 15 — Gestión de usuarios, monitoreo de errores y respaldo automático.
-- Ejecutar en Supabase > SQL Editor DESPUÉS de phase14. Es idempotente.
-- No borra datos existentes: agrega una columna a profiles, dos tablas y funciones.
--
-- Partes:
--   1. Monitoreo de errores en producción (tabla app_errors).
--   2. Gestión de usuarios desde la app (solo ADMIN).
--   3. Respaldo automático: instantáneas diarias de las tablas operativas.
--   4. Programación diaria con pg_cron (bloque aparte al final).

begin;

-- ============================================================================
-- 1. Monitoreo de errores
-- ============================================================================
create table if not exists public.app_errors (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid default auth.uid(),
  module text not null,
  action text not null,
  message text not null,
  error_code text,
  details jsonb not null default '{}'::jsonb
);
create index if not exists app_errors_created_idx on public.app_errors (created_at desc);

alter table public.app_errors enable row level security;
drop policy if exists "Admin read app errors" on public.app_errors;
create policy "Admin read app errors" on public.app_errors for select to authenticated using (public.is_admin());
drop policy if exists "Admin delete app errors" on public.app_errors;
create policy "Admin delete app errors" on public.app_errors for delete to authenticated using (public.is_admin());

-- Cualquier usuario autenticado registra errores, pero solo a través de esta función
-- (limita tamaños y descarta los registros de más de 90 días).
create or replace function public.log_client_error(
  p_module text, p_action text, p_message text, p_error_code text default null, p_details jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then return; end if;
  insert into public.app_errors (module, action, message, error_code, details)
  values (
    left(coalesce(p_module, 'Aplicación'), 120),
    left(coalesce(p_action, 'unknown'), 120),
    left(coalesce(p_message, 'Error desconocido'), 1000),
    left(p_error_code, 60),
    case when pg_column_size(p_details) > 20000 then jsonb_build_object('truncated', true) else coalesce(p_details, '{}'::jsonb) end
  );
  -- Limpieza ocasional para que la tabla no crezca sin límite.
  if random() < 0.02 then
    delete from public.app_errors where created_at < now() - interval '90 days';
  end if;
end;
$$;
revoke all on function public.log_client_error(text, text, text, text, jsonb) from public;
grant execute on function public.log_client_error(text, text, text, text, jsonb) to authenticated;

-- ============================================================================
-- 2. Gestión de usuarios (crear, editar, resetear contraseña, desactivar)
-- ============================================================================
alter table public.profiles add column if not exists active boolean not null default true;

-- Los administradores pueden leer todos los perfiles (para nombres en auditoría y usuarios).
drop policy if exists "Admin read all profiles" on public.profiles;
create policy "Admin read all profiles" on public.profiles for select to authenticated using (public.is_admin());

create or replace function public.admin_list_users()
returns table (
  id uuid, email text, full_name text, role text, active boolean,
  last_sign_in_at timestamptz, created_at timestamptz
)
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if not public.is_admin() then raise exception 'permission denied: solo ADMIN'; end if;
  return query
    select u.id, u.email::text, coalesce(p.full_name, '')::text, coalesce(p.role, '')::text,
           coalesce(p.active, true) and (u.banned_until is null or u.banned_until < now()),
           u.last_sign_in_at, u.created_at
    from auth.users u
    left join public.profiles p on p.id = u.id
    order by coalesce(p.full_name, u.email);
end;
$$;

create or replace function public.admin_create_user(p_email text, p_password text, p_full_name text, p_role text)
returns uuid
language plpgsql
security definer
set search_path = public, auth, extensions
as $$
declare
  v_id uuid := gen_random_uuid();
  v_email text := lower(trim(p_email));
  v_role text := upper(trim(p_role));
begin
  if not public.is_admin() then raise exception 'permission denied: solo ADMIN'; end if;
  if v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'Correo inválido.'; end if;
  if length(coalesce(p_password, '')) < 8 then raise exception 'La contraseña debe tener al menos 8 caracteres.'; end if;
  if v_role not in ('ADMIN', 'AUXILIARY', 'MANAGEMENT') then raise exception 'Rol inválido.'; end if;
  if exists (select 1 from auth.users where lower(email) = v_email) then
    raise exception 'Ya existe un usuario con ese correo.';
  end if;

  insert into auth.users (
    instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
    raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
    confirmation_token, recovery_token, email_change_token_new, email_change,
    email_change_token_current, phone_change_token, reauthentication_token
  ) values (
    '00000000-0000-0000-0000-000000000000', v_id, 'authenticated', 'authenticated', v_email,
    crypt(p_password, gen_salt('bf')), now(),
    '{"provider":"email","providers":["email"]}'::jsonb,
    jsonb_build_object('full_name', trim(p_full_name)), now(), now(),
    '', '', '', '', '', '', ''
  );

  insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
  values (
    gen_random_uuid(), v_id, v_id::text,
    jsonb_build_object('sub', v_id::text, 'email', v_email, 'email_verified', true),
    'email', now(), now(), now()
  );

  insert into public.profiles (id, full_name, role, active)
  values (v_id, left(trim(p_full_name), 120), v_role, true)
  on conflict (id) do update set full_name = excluded.full_name, role = excluded.role, active = true;

  return v_id;
end;
$$;

create or replace function public.admin_update_user(p_user_id uuid, p_full_name text, p_role text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_role text := upper(trim(p_role));
begin
  if not public.is_admin() then raise exception 'permission denied: solo ADMIN'; end if;
  if v_role not in ('ADMIN', 'AUXILIARY', 'MANAGEMENT') then raise exception 'Rol inválido.'; end if;
  if p_user_id = auth.uid() and v_role <> 'ADMIN' then
    raise exception 'No puedes quitarte el rol de administrador a ti mismo.';
  end if;
  insert into public.profiles (id, full_name, role)
  values (p_user_id, left(trim(p_full_name), 120), v_role)
  on conflict (id) do update set full_name = excluded.full_name, role = excluded.role;
end;
$$;

create or replace function public.admin_set_user_password(p_user_id uuid, p_password text)
returns void
language plpgsql
security definer
set search_path = public, auth, extensions
as $$
begin
  if not public.is_admin() then raise exception 'permission denied: solo ADMIN'; end if;
  if length(coalesce(p_password, '')) < 8 then raise exception 'La contraseña debe tener al menos 8 caracteres.'; end if;
  update auth.users set encrypted_password = crypt(p_password, gen_salt('bf')), updated_at = now() where id = p_user_id;
  if not found then raise exception 'Usuario no encontrado.'; end if;
end;
$$;

-- Desactivar bloquea el inicio de sesión (banned_until) y cierra sus sesiones abiertas.
create or replace function public.admin_set_user_active(p_user_id uuid, p_active boolean)
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if not public.is_admin() then raise exception 'permission denied: solo ADMIN'; end if;
  if p_user_id = auth.uid() and not p_active then raise exception 'No puedes desactivar tu propia cuenta.'; end if;
  update auth.users
    set banned_until = case when p_active then null else 'infinity'::timestamptz end, updated_at = now()
    where id = p_user_id;
  if not found then raise exception 'Usuario no encontrado.'; end if;
  update public.profiles set active = p_active where id = p_user_id;
  if not p_active then
    delete from auth.sessions where user_id = p_user_id;
    delete from auth.refresh_tokens where user_id = p_user_id::text;
  end if;
end;
$$;

revoke all on function public.admin_list_users() from public;
revoke all on function public.admin_create_user(text, text, text, text) from public;
revoke all on function public.admin_update_user(uuid, text, text) from public;
revoke all on function public.admin_set_user_password(uuid, text) from public;
revoke all on function public.admin_set_user_active(uuid, boolean) from public;
grant execute on function public.admin_list_users() to authenticated;
grant execute on function public.admin_create_user(text, text, text, text) to authenticated;
grant execute on function public.admin_update_user(uuid, text, text) to authenticated;
grant execute on function public.admin_set_user_password(uuid, text) to authenticated;
grant execute on function public.admin_set_user_active(uuid, boolean) to authenticated;

-- ============================================================================
-- 3. Respaldo automático: instantáneas de las tablas operativas dentro de la base.
--    Protegen ante borrados o errores; NO sustituyen una copia fuera de Supabase
--    (por eso la app permite descargarlas).
-- ============================================================================
create table if not exists public.backup_snapshots (
  id bigint generated by default as identity primary key,
  taken_at timestamptz not null default now(),
  kind text not null default 'AUTO' check (kind in ('AUTO', 'MANUAL')),
  row_counts jsonb not null default '{}'::jsonb,
  data jsonb not null default '{}'::jsonb
);
create index if not exists backup_snapshots_taken_idx on public.backup_snapshots (taken_at desc);

alter table public.backup_snapshots enable row level security;
drop policy if exists "Admin read backups" on public.backup_snapshots;
create policy "Admin read backups" on public.backup_snapshots for select to authenticated using (public.is_admin());

create or replace function public.take_backup_snapshot(p_kind text default 'AUTO')
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_tables text[] := array[
    'classrooms', 'students', 'guardians', 'student_guardians', 'profiles', 'school_settings',
    'attendance', 'presentation_controls', 'presentation_violations', 'notifications', 'alerts',
    'attendance_closures', 'student_absences', 'student_permissions', 'early_exits',
    'authorized_pickups', 'school_calendar', 'level_schedules', 'pension_payments'
  ];
  v_table text;
  v_rows jsonb;
  v_data jsonb := '{}'::jsonb;
  v_counts jsonb := '{}'::jsonb;
  v_id bigint;
begin
  -- Desde pg_cron no hay usuario (auth.uid() es null); desde la app solo ADMIN.
  if auth.uid() is not null and not public.is_admin() then raise exception 'permission denied: solo ADMIN'; end if;
  foreach v_table in array v_tables loop
    if to_regclass('public.' || v_table) is not null then
      execute format('select coalesce(jsonb_agg(t), ''[]''::jsonb) from public.%I t', v_table) into v_rows;
      v_data := v_data || jsonb_build_object(v_table, v_rows);
      v_counts := v_counts || jsonb_build_object(v_table, jsonb_array_length(v_rows));
    end if;
  end loop;

  insert into public.backup_snapshots (kind, row_counts, data)
  values (case when p_kind = 'MANUAL' then 'MANUAL' else 'AUTO' end, v_counts, v_data)
  returning id into v_id;

  -- Retención: las 7 automáticas más recientes y las 5 manuales más recientes.
  delete from public.backup_snapshots where kind = 'AUTO'
    and id not in (select id from public.backup_snapshots where kind = 'AUTO' order by taken_at desc limit 7);
  delete from public.backup_snapshots where kind = 'MANUAL'
    and id not in (select id from public.backup_snapshots where kind = 'MANUAL' order by taken_at desc limit 5);
  return v_id;
end;
$$;
revoke all on function public.take_backup_snapshot(text) from public;
grant execute on function public.take_backup_snapshot(text) to authenticated;

commit;

-- ============================================================================
-- 4. Programación diaria (1:00 a. m. hora de Perú = 06:00 UTC).
--    Si este bloque da error, activa la extensión "pg_cron" en
--    Supabase > Database > Extensions y vuelve a ejecutar SOLO este bloque.
--    Sin él todo lo demás funciona: el admin puede crear copias con un clic.
-- ============================================================================
create extension if not exists pg_cron with schema pg_catalog;
select cron.unschedule(jobid) from cron.job where jobname = 'tesla-daily-backup';
select cron.schedule('tesla-daily-backup', '0 6 * * *', $$select public.take_backup_snapshot('AUTO')$$);
