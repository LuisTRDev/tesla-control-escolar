--    personas autorizadas): lectura para todos, escritura solo ADMIN.
-- ============================================================================
alter table public.student_absences enable row level security;
alter table public.student_permissions enable row level security;
alter table public.authorized_pickups enable row level security;
alter table public.early_exits enable row level security;
alter table public.school_calendar enable row level security;
alter table public.level_schedules enable row level security;

