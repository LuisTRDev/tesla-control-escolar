create policy "Authenticated manage absences" on public.student_absences for all to authenticated using (true) with check (true);

drop policy if exists "Authenticated manage permissions" on public.student_permissions;
create policy "Authenticated manage permissions" on public.student_permissions for all to authenticated using (true) with check (true);

drop policy if exists "Authenticated manage early exits" on public.early_exits;
create policy "Authenticated manage early exits" on public.early_exits for all to authenticated using (true) with check (true);

drop policy if exists "Authenticated read pickups" on public.authorized_pickups;
drop policy if exists "Admin write pickups" on public.authorized_pickups;
create policy "Authenticated read pickups" on public.authorized_pickups for select to authenticated using (true);
create policy "Admin write pickups" on public.authorized_pickups for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Authenticated read calendar" on public.school_calendar;
drop policy if exists "Admin write calendar" on public.school_calendar;
create policy "Authenticated read calendar" on public.school_calendar for select to authenticated using (true);
create policy "Admin write calendar" on public.school_calendar for all to authenticated using (public.is_admin()) with check (public.is_admin());

