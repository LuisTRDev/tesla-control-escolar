begin;

-- ============================================================================
-- 1. Tardanza justificada: la marca sigue siendo LATE pero queda justificada
--    (no genera notificación ni cuenta como reincidencia).
-- ============================================================================
alter table public.attendance
  add column if not exists justified boolean not null default false,
  add column if not exists justification_reason text,
  add column if not exists justification_document text,
  add column if not exists justified_by uuid,
  add column if not exists justified_by_name text,
  add column if not exists justified_at timestamptz;

-- La notificación automática de tardanza solo para tardanzas NO justificadas.
drop trigger if exists trg_auto_late_notification on public.attendance;
create trigger trg_auto_late_notification
after insert or update of status, entry_time on public.attendance
for each row
when (new.status = 'LATE' and not new.justified)
execute function public.ensure_late_notification_from_attendance();

-- ============================================================================
-- 2. Faltas del día (las genera el botón "Cerrar día").
--    status: UNJUSTIFIED (falta), JUSTIFIED (falta justificada), PERMISSION (con permiso previo)
-- ============================================================================
create table if not exists public.student_absences (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete cascade,
  classroom_id bigint,
  date date not null,
  status text not null default 'UNJUSTIFIED' check (status in ('UNJUSTIFIED', 'JUSTIFIED', 'PERMISSION')),
  justification_reason text,
  justification_document text,
  justified_by uuid,
  justified_by_name text,
  justified_at timestamptz,
  created_at timestamptz not null default now(),
  unique (student_id, date)
);
create index if not exists student_absences_date_idx on public.student_absences (date);

-- Si el alumno llega después de cerrado el día, su falta desaparece sola.
create or replace function public.remove_absence_on_attendance()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from public.student_absences where student_id = new.student_id and date = new.date;
  return new;
end;
$$;

drop trigger if exists trg_remove_absence_on_attendance on public.attendance;
create trigger trg_remove_absence_on_attendance
after insert on public.attendance
for each row execute function public.remove_absence_on_attendance();

-- ============================================================================
-- 3. Permisos anticipados ("no vendrá el viernes", "llegará tarde el lunes").
--    kind: ABSENCE (no asistirá) | LATE (llegará tarde)
-- ============================================================================
create table if not exists public.student_permissions (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete cascade,
  date_from date not null,
  date_to date not null,
  kind text not null check (kind in ('ABSENCE', 'LATE')),
  reason text not null,
  document_path text,
  created_by uuid default auth.uid(),
  created_by_name text,
  created_at timestamptz not null default now(),
  check (date_to >= date_from)
);
create index if not exists student_permissions_range_idx on public.student_permissions (date_from, date_to);

-- ============================================================================
-- 4. Personas autorizadas a recoger al alumno (además de sus apoderados).
-- ============================================================================
create table if not exists public.authorized_pickups (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete cascade,
  full_name text not null,
  dni text,
  relationship text,
  phone text,
  created_at timestamptz not null default now()
);
create index if not exists authorized_pickups_student_idx on public.authorized_pickups (student_id);

-- ============================================================================
-- 5. Salidas anticipadas.
-- ============================================================================
create table if not exists public.early_exits (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete cascade,
  date date not null,
  exit_time time not null,
  picked_up_by_name text not null,
  picked_up_by_dni text,
  relationship text,
  reason text not null,
  is_authorized_person boolean not null default false,
  recorded_by uuid default auth.uid(),
  recorded_by_name text,
  created_at timestamptz not null default now()
);
create index if not exists early_exits_date_idx on public.early_exits (date);

-- ============================================================================
-- 6. Calendario escolar: días sin clases (no se generan faltas).
-- ============================================================================
create table if not exists public.school_calendar (
  date date primary key,
  kind text not null check (kind in ('HOLIDAY', 'VACATION', 'NO_CLASSES')),
  description text not null default ''
);

-- ============================================================================
-- 7. Horario por nivel (si no hay fila para un nivel, se usa el horario general).
-- ============================================================================
create table if not exists public.level_schedules (
  level text primary key check (level in ('Primaria', 'Secundaria')),
  entry_limit time not null,
  tolerance_enabled boolean not null default false,
  tolerance_minutes int not null default 0 check (tolerance_minutes between 0 and 60)
);

-- ============================================================================
-- 8. Permisos de acceso (RLS).
--    Operación diaria (faltas, justificaciones, permisos, salidas): todo usuario
