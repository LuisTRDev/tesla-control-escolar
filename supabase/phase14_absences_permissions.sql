create policy "Authenticated write level schedules" on public.level_schedules for all to authenticated using (true) with check (true);

-- ============================================================================
-- 9. Cerrar y reabrir el día (botón en "Resumen / cierre").
--    Cerrar: los alumnos activos sin ingreso pasan a falta, o a PERMISSION si
--    tienen permiso de inasistencia ese día. No hace nada en días sin clases.
--    Reabrir: borra las faltas sin justificar de ese día (las justificadas y
--    los permisos se conservan) para corregir un cierre hecho antes de tiempo.
-- ============================================================================
create or replace function public.close_attendance_day(p_date date, p_classroom_id bigint default null)
returns table (absences int, permissions int)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_absences int := 0;
  v_permissions int := 0;
  v_room record;
begin
  if auth.uid() is null then
    raise exception 'permission denied';
  end if;
  if exists (select 1 from public.school_calendar c where c.date = p_date) then
    raise exception 'Ese día está marcado como día sin clases en el calendario escolar.';
  end if;

  with inserted as (
    insert into public.student_absences (student_id, classroom_id, date, status, justification_reason)
    select s.id, s.classroom_id, p_date,
           case when p.id is not null then 'PERMISSION' else 'UNJUSTIFIED' end,
           p.reason
    from public.students s
    left join lateral (
      select sp.id, sp.reason from public.student_permissions sp
      where sp.student_id = s.id and sp.kind = 'ABSENCE' and p_date between sp.date_from and sp.date_to
      order by sp.id desc limit 1
    ) p on true
    where coalesce(s.is_active, true)
      and (p_classroom_id is null or s.classroom_id = p_classroom_id)
      and not exists (select 1 from public.attendance a where a.student_id = s.id and a.date = p_date)
    on conflict (student_id, date) do nothing
    returning status
  )
  select count(*) filter (where status = 'UNJUSTIFIED'), count(*) filter (where status = 'PERMISSION')
  into v_absences, v_permissions
  from inserted;

  -- Mantiene el registro de cierre que usa el Resumen diario. Si la tabla tiene
  -- otras columnas obligatorias, se ignora sin afectar las faltas.
  for v_room in
    select c.id from public.classrooms c where p_classroom_id is null or c.id = p_classroom_id
  loop
    begin
      insert into public.attendance_closures (classroom_id, date) values (v_room.id, p_date);
    exception when others then
      null;
    end;
  end loop;

  return query select v_absences, v_permissions;
end;
$$;

create or replace function public.reopen_attendance_day(p_date date, p_classroom_id bigint default null)
returns int
language plpgsql
security definer
set search_path = public
as $$
declare
  v_deleted int;
begin
  if auth.uid() is null then
    raise exception 'permission denied';
  end if;
  delete from public.student_absences
  where date = p_date
    and status = 'UNJUSTIFIED'
    and (p_classroom_id is null or classroom_id = p_classroom_id);
  get diagnostics v_deleted = row_count;

  begin
    delete from public.attendance_closures
    where date = p_date and (p_classroom_id is null or classroom_id = p_classroom_id);
  exception when others then
    null;
  end;
  return v_deleted;
end;
$$;

revoke all on function public.close_attendance_day(date, bigint) from public, anon;
revoke all on function public.reopen_attendance_day(date, bigint) from public, anon;
grant execute on function public.close_attendance_day(date, bigint) to authenticated;
grant execute on function public.reopen_attendance_day(date, bigint) to authenticated;

